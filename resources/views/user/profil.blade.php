      <h2 class="h5">Data Dasar Keluarga</h2>
      <p>Jumlah Kepala Keluarga Padukuhan Dowangan terdiri dari <strong>486 Kepala Keluarga</strong>, dengan jumlah warga sebanyak <strong>1319 orang</strong>. Dari jumlah tersebut terdapat <strong>640 orang (48,52%)</strong> berjenis kelamin laki-laki dan <strong>679 orang (51,48%)</strong> berjenis kelamin perempuan.</p>
