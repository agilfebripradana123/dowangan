    <article class="mb-4">
      <h2 class="h5">Penguasaan Aset & Pekerjaan</h2>
      <p>Untuk mendukung kegiatan ekonomi masyarakat, mayoritas penduduk bekerja sebagai <strong>buruh lepas</strong>. Selain itu terdapat pula pengusaha (pedagang, pemilik kost, pemilik usaha industri, pengusaha laundry), petani, Pegawai Negeri Sipil, dan profesi lainnya.</p>
    </article>

    <article class="mb-4">
      <h2 class="h5">Potensi Padukuhan</h2>

      <h3 class="h6 mt-3">1. Sumber Daya Alam dan Buatan</h3>
      <p>Luas wilayah Padukuhan Dowangan adalah <strong>46,7 Ha</strong> dengan batas wilayah:</p>
      <ul>
        <li><strong>Timur :</strong> berbatasan dengan Dusun Sukunan</li>
        <li><strong>Selatan :</strong> berbatasan dengan Dusun Kaliabu</li>
        <li><strong>Barat :</strong> berbatasan dengan Kalurahan Ambarketawang</li>
        <li><strong>Utara :</strong> berbatasan dengan Kalurahan Nogotirto</li>
      </ul>
      <p>Terdapat sumber mata air bersejarah yang dulu dipakai sebagai pemandian Putri Keraton Yogyakarta. Saat ini sumber tersebut telah direnovasi beberapa kali dan digunakan warga sebagai fasilitas umum untuk pemandian dan kebutuhan sehari-hari.</p>

      <h3 class="h6 mt-3">2. Sumber Daya Manusia</h3>
      <p>Komposisi pekerjaan warga (perkiraan):</p>
      <ul>
        <li>30% buruh harian lepas</li>
        <li>15% karyawan swasta</li>
        <li>13% petani</li>
        <li>12% ASN</li>
        <li>10% pedagang</li>
        <li>8% pensiunan</li>
        <li>5% anggota TNI/POLRI</li>
        <li>4% honorer</li>
        <li>3% lain-lain</li>
      </ul>
      <p>Tingkat pendidikan: <strong>Sarjana 13%</strong>, <strong>SLTA 54%</strong>, <strong>SLTP 18%</strong>, <strong>SD 13%</strong>, <strong>TK 2%</strong>. Agama: <strong>Islam 94%</strong>, Kristen 4%, Katolik 2%.</p>
    </article>

    <article class="mb-4">
      <h2 class="h5">Kelembagaan</h2>
      <p>Padukuhan Dowangan terdiri dari <strong>2 Rukun Warga (RW)</strong> — RW 16 (Dusun Dowangan) dan RW 17 (Desa Kradenan) — dengan total <strong>6 Rukun Tetangga (RT)</strong>. Beberapa kelompok masyarakat aktif antara lain:</p>
      <ul>
        <li>Kelompok Masyarakat Tani Gotong Royong</li>
        <li>Kelompok Peternak Kambing (Mendo Ngremboko)</li>
        <li>KWT Rukun</li>
        <li>Kelompok Perikanan Mina Mukti</li>
        <li>Bank Sampah Kradenan Berseri</li>
        <li>Kelompok Seni Karawitan Simo Laras</li>
      </ul>
    </article>

    <article class="mb-2">
      <h2 class="h5">Sarana & Prasarana</h2>
      <p>Fasilitas yang ada di Dusun Dowangan antara lain:</p>
      <ul>
        <li>Sumber mata air dan pemandian umum (bersejarah)</li>
        <li>Fasilitas pendidikan: <strong>Universitas Nahdatul Ulama (UNU)</strong>, SD Negeri Banyuraden, TK Pamardi Siwi, dan Tempat Penitipan Anak (TPA)</li>
        <li>Beberapa cagar budaya (termasuk sebuah rumah sakit era Belanda yang kini disewakan sebagai pabrik meubel dengan syarat menjaga keaslian bangunan)</li>
        <li>Makam umum yang masih aktif dan sejumlah situs bersejarah (mis. makam Kasepuhan, rumah joglo)</li>
      </ul>
      <p>Beberapa bangunan cagar budaya masih dalam proses pendataan atau perundingan untuk perlindungan resmi.</p>
    </article>

    <article class="mb-4">
      <h2 class="h5">Perkembangan Padukuhan</h2>

      <h3 class="h6 mt-3">Sejarah Singkat</h3>
      <p>Nama Dukuh Dowangan telah ada sejak lama dan perkembangan administratifnya terkait pembentukan Desa Banyuraden.</p>

      <h3 class="h6 mt-3">Trend Perkembangan Wilayah</h3>
      <p>Pembangunan fisik di Dowangan pesat — didorong hadirnya fasilitas pendidikan, industri, dan akses jalan (ringroad). Muncul gedung usaha, kost, dan bisnis pendukung lainnya. Lokasi ini juga terpengaruh rencana pembangunan Jalan Tol Jogja–Bandara NYIA, dengan <strong>270 bidang terdampak</strong>, yang diharapkan mendorong perkembangan ekonomi dan infrastruktur setempat.</p>
    </article>

    <article class="mb-4">
      <h2 class="h5">Data Pertanahan</h2>
      <p>Jumlah bidang tanah: <strong>856 bidang</strong>, dengan rincian <strong>786 bidang bersertifikat</strong> dan <strong>70 bidang belum bersertifikat</strong>. Luas Sultan Ground (SG) sekitar <strong>4 Ha</strong> yang sebagian dikuasai warga turun-temurun (3–4 generasi).</p>
    </article>

    <article class="mb-4">
      <h2 class="h5">Peran Serta Masyarakat</h2>

      <h3 class="h6 mt-3">Kondisi Ekonomi</h3>
      <p>Perekonomian berbasis mata pencaharian warga (disampaikan sebelumnya). Kelompok masyarakat seperti Pokmas Tani, Pokmas Peternak, KWT, perikanan, dan bank sampah berkontribusi pada ekonomi lokal.</p>

      <h3 class="h6 mt-3">Kondisi Sosial</h3>
      <p>Kegiatan sosial rutin: posyandu anak & lansia, PKK, arisan (bulanan), serta Ronda malam dengan jadwal bergilir warga.</p>

      <h3 class="h6 mt-3">Kondisi Budaya</h3>
      <p>Kegiatan kebudayaan aktif meliputi latihan karawitan, tari, dan wayang—dijalankan sanggar lokal seperti Sanggar Tari Cipto Nugroho dan sanggar Karawitan Simo Laras. Beberapa grup sering diundang pada acara pemerintah maupun swasta.</p>
